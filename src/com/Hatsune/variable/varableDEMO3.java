package com.Hatsune.variable;

import java.util.Scanner;

public class varableDEMO3 {
    static void main() {
        //创建一个Scanner对象
        Scanner sc = new Scanner(System.in);
        //从键盘接收一个整数
        int num = sc.nextInt();
        System.out.println(num);
        //从键盘接收一个浮点数
        double num2 = sc.nextDouble();
        System.out.println(num2);
        //从键盘接收一个字符串
        String c = sc.next();
        System.out.println(c);



    }
}
