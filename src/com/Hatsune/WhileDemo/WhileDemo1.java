package com.Hatsune.WhileDemo;

public class WhileDemo1 {
    static void main() {
        /*while循环的格式:
        while(条件判断语句){
        循环体语句
        条件控制语句
        }*/
        //i++放在代码最后
        int i = 1;
        while(i<=10) {
            System.out.println(i);
            i++;
        }
    }
}
