package com.Hatsune.Operater;

public class Operater6 {
    static void main() {
        int a = 10;
        int b = 20;
        // 等价于 a = a + b;
        a += b;
        System.out.println(a);
        System.out.println(b);
        // 等价于 a = a - b;
        a -= b;
        System.out.println(a);
        // 等价于 a = a * b;
        a *= b;
        System.out.println(a);
        // 等价于 a = a / b;
        a /= b;
        System.out.println(a);
        // 等价于 a = a % b;
        a %= b;
        System.out.println(a);

    }
}
